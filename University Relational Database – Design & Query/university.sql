-- University information system (Oracle SQL)
-- Students, instructors, courses, and enrollments are separated into
-- normalized tables; enrollment uses a composite key to prevent duplicates.

CREATE TABLE Students (
    student_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    name       VARCHAR2(100) NOT NULL,
    email      VARCHAR2(255) NOT NULL,
    age        NUMBER(3) NOT NULL,
    CONSTRAINT pk_students PRIMARY KEY (student_id),
    CONSTRAINT uq_students_email UNIQUE (email),
    CONSTRAINT chk_students_age CHECK (age > 17)
);

CREATE TABLE Instructors (
    instructor_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    name          VARCHAR2(100) NOT NULL,
    department    VARCHAR2(100) NOT NULL,
    CONSTRAINT pk_instructors PRIMARY KEY (instructor_id)
);

CREATE TABLE Courses (
    course_id     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    title         VARCHAR2(150) NOT NULL,
    credits       NUMBER(2) NOT NULL,
    instructor_id NUMBER NOT NULL,
    CONSTRAINT pk_courses PRIMARY KEY (course_id),
    CONSTRAINT chk_courses_credits CHECK (credits > 0),
    CONSTRAINT fk_courses_instructor FOREIGN KEY (instructor_id)
        REFERENCES Instructors (instructor_id)
);

CREATE TABLE Enrollments (
    student_id NUMBER NOT NULL,
    course_id  NUMBER NOT NULL,
    grade      VARCHAR2(2),
    CONSTRAINT pk_enrollments PRIMARY KEY (student_id, course_id),
    CONSTRAINT fk_enrollments_student FOREIGN KEY (student_id)
        REFERENCES Students (student_id) ON DELETE CASCADE,
    CONSTRAINT fk_enrollments_course FOREIGN KEY (course_id)
        REFERENCES Courses (course_id) ON DELETE CASCADE,
    CONSTRAINT chk_enrollments_grade CHECK (
        grade IS NULL OR grade IN ('A', 'B', 'C', 'D', 'F')
    )
);

