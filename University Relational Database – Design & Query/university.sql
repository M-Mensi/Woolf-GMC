-- Students enrolled in Database Systems.
SELECT s.student_id, s.name, s.email
FROM Students s
JOIN Enrollments e ON e.student_id = s.student_id
JOIN Courses c ON c.course_id = e.course_id
WHERE c.title = 'Database Systems'
ORDER BY s.student_id;

-- Every course and its instructor.
SELECT c.course_id, c.title, i.name AS instructor_name
FROM Courses c
LEFT JOIN Instructors i ON i.instructor_id = c.instructor_id
ORDER BY c.course_id;

-- Students who are not enrolled in any course.
SELECT s.student_id, s.name, s.email
FROM Students s
WHERE NOT EXISTS (
    SELECT 1
    FROM Enrollments e
    WHERE e.student_id = s.student_id
)
ORDER BY s.student_id;

